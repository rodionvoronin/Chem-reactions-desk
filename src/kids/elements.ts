export const CARD_MAP: Record<string, ElementCard> = Object.fromEntries(CARDS.map((c) => [c.symbol, c]))

const ELEMENT_MAP: Record<string, Element> = Object.fromEntries(ELEMENTS.map((e) => [e.symbol, e]))

/** Номер, название и масса — из таблицы Менделеева приложения */
export function elementOf(symbol: string): Element {
  return ELEMENT_MAP[symbol]
}

/** Цвета карточек: металлы — тёплые, неметаллы — холодные */
export function cardColor(card: ElementCard): { bg: string; fg: string } {
  return card.metal
    ? { bg: '#FFE0B2', fg: '#E65100' }
    : { bg: '#C5E1FF', fg: '#0D47A1' }
}
