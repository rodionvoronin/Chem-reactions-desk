export const CASE_MAP: Record<string, Case> = Object.fromEntries(CASES.map((c) => [c.id, c]))

/** Задачи дела в том порядке, в каком их проходят */
export function caseTasks(item: Case): Task[] {
  return item.steps.map((s) => TASK_MAP[s.taskId]).filter(Boolean)
}

/** Сложность дела — по самому трудному его шагу */
export function caseDifficulty(item: Case): number {
  return Math.max(1, ...caseTasks(item).map((t) => t.difficulty))
}
