// ── Дела: связанные задачи с сюжетом и общим ответом ──────────────────────────
//
// Отдельная задача заканчивается вместе с ответом, и связи между задачами
// ученик не строит. Дело собирает три-четыре задачи в одно расследование:
// каждый шаг даёт улику, а финальный вопрос решается только по всем уликам
// сразу. Формат химического квеста — самый доказанный в исследованиях по
// вовлечению, и здесь он ложится на уже готовые типы задач.
//
// Шаги ссылаются на задачи банка по id, поэтому химия остаётся ровно той,
// что уже проверена check:tasks. Утверждения сюжета, опирающиеся на реакции,
// вынесены в facts и сверяются с таблицей реакций в check:cases.

import { TASK_MAP } from './bank'
import { Task } from './types'

/** Утверждение сюжета, которое обязано подтверждаться таблицей реакций */
export interface CaseFact {
  /** Реагенты, которые смешивают */
  inputs: string[]
  dry?: boolean
  /** Что должно наблюдаться */
  expect: 'precipitate' | 'gas' | 'both' | 'any'
  /** Зачем это утверждение нужно делу */
  why: string
}

export interface CaseStep {
  taskId: string
  /** Что происходит по сюжету перед этим шагом */
  intro: string
  /** Улика, которая открывается после решения */
  evidence: string
}

export interface Case {
  id: string
  title: string
  /** Завязка расследования */
  brief: string
  steps: CaseStep[]
  /** Финальный вопрос — решается только по всем уликам сразу */
  question: string
  options: string[]
  /** Индекс верного варианта */
  answer: number
  /** Объяснение после ответа */
  explanation: string
  facts: CaseFact[]
}

